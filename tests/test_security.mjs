import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
if(!globalThis.crypto)Object.defineProperty(globalThis,'crypto',{value:webcrypto});
const {default:worker}=await import('../security/worker.mjs');
const origin='https://alta.example';
const env={ALTA_SITE_PASSWORD:'test-password-only-123456',ALTA_SESSION_SECRET:'test-session-key-only-1234567890123456789',RATE_LIMITER:{limit:async()=>({success:true})},ASSETS:{fetch:async()=>new Response('map')}};
const request=(path,options)=>new Request(origin+path,options);
assert.equal((await worker.fetch(request('/'),{})).status,503);
assert.equal((await worker.fetch(request('/admin'),env)).status,404);
assert.equal((await worker.fetch(request('/production/JP.json'),env)).status,303);
const post=password=>({method:'POST',headers:{Origin:origin,'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({password})});
assert.equal((await worker.fetch(request('/auth/login',post('wrong')),env)).status,401);
const bad=post(env.ALTA_SITE_PASSWORD);bad.headers.Origin='https://other.example';
assert.equal((await worker.fetch(request('/auth/login',bad),env)).status,403);
const res=await worker.fetch(request('/auth/login',post(env.ALTA_SITE_PASSWORD)),env);
assert.equal(res.status,303);
const raw=res.headers.get('set-cookie'),cookie=raw.split(';')[0];
assert.match(raw,/HttpOnly/);assert.match(raw,/Secure/);assert.match(raw,/SameSite=Strict/);
assert.equal((await worker.fetch(request('/production/JP.json',{headers:{Cookie:cookie}}),env)).status,200);
assert.equal((await worker.fetch(request('/production/JP.json',{headers:{Cookie:cookie+'0'}}),env)).status,303);
assert.equal((await worker.fetch(request('/',{headers:{Cookie:cookie}}),{...env,ALTA_SITE_PASSWORD:'rotated-test-password-123456'})).status,303);
assert.equal((await worker.fetch(request('/auth/login',post(env.ALTA_SITE_PASSWORD)),{...env,RATE_LIMITER:{limit:async()=>({success:false})}})).status,429);
console.log('Shared-password auth: closed config, routes, CSRF, login, cookie, tamper, rotation, limiter passed');
